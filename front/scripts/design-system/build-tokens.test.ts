import { buildTokens, camelKey, tObject, TokenSource } from './build-tokens';

// Six tokens: two tiers, a reference, a tenant slot, a back-office proposal.
const mini: TokenSource = {
  primitive: {
    color: {
      $extensions: { gv: { prefix: '' } },
      'grey-800': {
        $type: 'color',
        $value: '#333333',
        $extensions: { gv: { legacy: ['colors.grey800'] } },
      },
    },
    radius: {
      '2': { $type: 'dimension', $value: '8px' },
      '3': { $type: 'dimension', $value: '12px' },
    },
  },
  semantic: {
    color: {
      $extensions: { gv: { prefix: '' } },
      'text-primary': {
        $type: 'color',
        $value: '{primitive.color.grey-800}',
        $extensions: { gv: { legacy: ['colors.textPrimary'] } },
      },
      'color-tenant-primary': {
        $type: 'color',
        $value: '#ef0071',
        $extensions: {
          gv: { tenant: 'primary', legacy: ['theme.colors.tenantPrimary'] },
        },
      },
    },
    radius: {
      $extensions: { gv: { prefix: '' } },
      'radius-control': {
        $type: 'dimension',
        $value: '3px',
        $description: 'Controls.',
        $extensions: {
          gv: {
            backOffice: '{primitive.radius.2}',
            legacy: ['theme.borderRadius', 'stylingConsts.borderRadius'],
          },
        },
      },
    },
  },
};

const HEADER =
  '/* Generated by scripts/design-system/build-tokens.ts from tokens.source.json. Do not edit. */\n';

describe('buildTokens', () => {
  it('renders :root with every token and no proposal', () => {
    const { css } = buildTokens(mini);
    expect(css).toBe(
      HEADER +
        '\n' +
        ':root {\n' +
        '  --gv-grey-800: #333333;\n' +
        '  --gv-radius-2: 8px;\n' +
        '  --gv-radius-3: 12px;\n' +
        '  --gv-text-primary: var(--gv-grey-800);\n' +
        '  --gv-color-tenant-primary: var(--gv-tenant-primary, #ef0071);\n' +
        '  --gv-radius-control: 3px;\n' +
        '}\n'
    );
  });

  it('nests t by category with var() strings', () => {
    expect(tObject(mini)).toEqual({
      color: {
        grey800: 'var(--gv-grey-800)',
        textPrimary: 'var(--gv-text-primary)',
        tenantPrimary: 'var(--gv-color-tenant-primary)',
      },
      radius: {
        '2': 'var(--gv-radius-2)',
        '3': 'var(--gv-radius-3)',
        control: 'var(--gv-radius-control)',
      },
    });
  });

  it('emits t, cssVar and TokenName in tokens.ts', () => {
    const { ts } = buildTokens(mini);
    expect(ts).not.toContain('MODES');
    expect(ts).toContain("| '--gv-radius-control'");
    expect(ts).toContain(
      'export const cssVar = (name: TokenName): string => `var(${name})`;'
    );
    expect(ts).toContain("control: 'var(--gv-radius-control)'");
    expect(ts).toContain('} as const;');
  });

  it('writes one meta entry per token with resolved values', () => {
    const { meta } = buildTokens(mini);
    expect(meta).toHaveLength(6);
    const control = meta.find((m) => m.name === '--gv-radius-control');
    expect(control).toMatchObject({
      category: 'radius',
      tier: 2,
      value: '3px',
      backOffice: '8px',
      legacy: ['theme.borderRadius', 'stylingConsts.borderRadius'],
      description: 'Controls.',
      type: 'dimension',
    });
    const text = meta.find((m) => m.name === '--gv-text-primary');
    expect(text?.value).toBe('#333333');
    expect(text).not.toHaveProperty('backOffice');
    expect(meta.find((m) => m.name === '--gv-grey-800')?.tier).toBe(1);
  });

  it('resolves a reference to var(--gv-radius-2)', () => {
    const { css } = buildTokens({
      ...mini,
      semantic: {
        radius: {
          $extensions: { gv: { prefix: '' } },
          'radius-control': {
            $type: 'dimension',
            $value: '{primitive.radius.2}',
          },
        },
      },
    });
    expect(css).toContain('--gv-radius-control: var(--gv-radius-2);');
  });

  it('renders a tenant slot with its fallback and records the slot', () => {
    const { css, meta } = buildTokens(mini);
    expect(css).toContain(
      '--gv-color-tenant-primary: var(--gv-tenant-primary, #ef0071);'
    );
    const slot = meta.find((m) => m.name === '--gv-color-tenant-primary');
    expect(slot?.value).toBe('#ef0071');
    expect(slot?.tenant).toBe('primary');
  });

  it('resolves a proposed back-office value through references, never into the CSS', () => {
    const src: TokenSource = {
      primitive: {
        font: {
          $extensions: { gv: { prefix: '' } },
          'fs-xl': {
            $type: 'dimension',
            $value: '21px',
            $extensions: { gv: { backOffice: '20px' } },
          },
        },
      },
      semantic: {
        text: {
          $extensions: { gv: { prefix: '' } },
          'type-h3-size': {
            $type: 'dimension',
            $value: '{primitive.font.fs-xl}',
          },
        },
      },
    };
    const { css, meta } = buildTokens(src);
    expect(css).not.toContain('20px');
    expect(meta.find((m) => m.name === '--gv-type-h3-size')).toMatchObject({
      value: '21px',
      backOffice: '20px',
    });
  });

  it('follows a proposed slot value to its readers', () => {
    const src: TokenSource = {
      semantic: {
        color: {
          $extensions: { gv: { prefix: '' } },
          'tenant-primary': {
            $type: 'color',
            $value: '#ef0071',
            $extensions: { gv: { slot: true, backOffice: '#044D6C' } },
          },
          'color-tenant-primary': {
            $type: 'color',
            $value: '#ef0071',
            $extensions: { gv: { tenant: 'primary' } },
          },
        },
      },
    };
    const { css, meta } = buildTokens(src);
    expect(css).toContain(
      '--gv-color-tenant-primary: var(--gv-tenant-primary, #ef0071);'
    );
    expect(
      meta.find((m) => m.name === '--gv-color-tenant-primary')
    ).toMatchObject({ value: '#ef0071', backOffice: '#044D6C' });
    // Slots are runtime inputs, read through the semantic token.
    expect(tObject(src)).toEqual({
      color: { tenantPrimary: 'var(--gv-color-tenant-primary)' },
    });
  });

  it('leaves deprecated tokens out of t but keeps them in the CSS', () => {
    const src: TokenSource = {
      semantic: {
        radius: {
          $extensions: { gv: { prefix: '' } },
          radius: { $type: 'dimension', $value: '3px', $deprecated: true },
          'radius-control': { $type: 'dimension', $value: '3px' },
        },
      },
    };
    expect(buildTokens(src).css).toContain('--gv-radius: 3px;');
    expect(tObject(src)).toEqual({
      radius: { control: 'var(--gv-radius-control)' },
    });
  });

  it('throws on a bad name', () => {
    const src: TokenSource = {
      primitive: {
        color: { Bad_Name: { $type: 'color', $value: '#000' } },
      },
    };
    expect(() => buildTokens(src)).toThrow(/--gv-color-Bad_Name/);
  });

  it('throws on an unknown reference, a cycle and an unknown category', () => {
    expect(() =>
      buildTokens({
        primitive: { space: { '1': { $type: 'dimension', $value: '{x.y}' } } },
      })
    ).toThrow(/unknown reference \{x\.y\}/);
    expect(() =>
      buildTokens({
        primitive: {
          space: {
            '1': { $type: 'dimension', $value: '{primitive.space.2}' },
            '2': { $type: 'dimension', $value: '{primitive.space.1}' },
          },
        },
      })
    ).toThrow(/cycle/);
    expect(() =>
      buildTokens({
        primitive: { size: { '1': { $type: 'dimension', $value: '1px' } } },
      })
    ).toThrow(/unknown category size/);
  });

  it('throws when two tokens share a t key', () => {
    expect(() =>
      buildTokens({
        semantic: {
          color: {
            $extensions: { gv: { prefix: '' } },
            'text-heading': { $type: 'color', $value: '#474747' },
            'color-text-heading': { $type: 'color', $value: '#333333' },
          },
        },
      })
    ).toThrow(/t\.color\.textHeading/);
  });

  it('is deterministic', () => {
    expect(buildTokens(mini)).toEqual(buildTokens(mini));
  });
});

describe('camelKey', () => {
  it('drops the category prefix and camel-cases the rest', () => {
    expect(camelKey('color-text-heading', 'color')).toBe('textHeading');
    expect(camelKey('cool-grey-700', 'color')).toBe('coolGrey700');
    expect(camelKey('space-12', 'space')).toBe('12');
    expect(camelKey('shadow', 'shadow')).toBe('shadow');
  });
});
